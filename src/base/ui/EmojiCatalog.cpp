std::vector<EmojiCategory> EmojiCatalog::BuildWithRecent(const std::vector<std::string>& recent_emojis) {
  std::vector<EmojiCategory> out;
  if (!recent_emojis.empty()) {
    EmojiCategory recent;
    recent.id = std::string(kRecentlyUsedId);
    recent.label = "Recently used";
    recent.rail_glyph = "🕒";
    recent.glyphs = recent_emojis;
    if (recent.glyphs.size() > kRecentCap) {
      recent.glyphs.resize(kRecentCap);
    }
    out.push_back(std::move(recent));
  }
  const auto& static_cats = StaticCategories();
  out.insert(out.end(), static_cats.begin(), static_cats.end());
  return out;
}

void EmojiCatalog::TouchRecent(std::vector<std::string>& recent, const std::string& glyph) {
  const std::string key = NormalizeEmojiKey(glyph);
  if (key.empty()) {
    return;
  }
  recent.erase(std::remove_if(recent.begin(), recent.end(),
                              [&](const std::string& e) { return NormalizeEmojiKey(e) == key; }),
               recent.end());
  recent.insert(recent.begin(), key);
  if (recent.size() > kRecentCap) {
    recent.resize(kRecentCap);
  }
}

