#!/usr/bin/env python3
"""Copy the phone's message-bubble rules into the wide layout (desktop, wide iPad).

The phone styles its conversation under `.shell-chat-overlay` (components.rcss and colors.rcss.tmpl). The wide layout has no
such root, so a bubble there would fall back to the plain rules. This script copies every `.shell-chat-overlay` rule that
styles message content (bubbles, tails, picture / video / file / voice cards, footers, quotes, reactions, system lines,
date pills, group names) with the root swapped to `.shell-body--wide`, so a message looks the same on both. The rules for
the message list's own layout (`.messages`, `.message-row`), the header and the composer are not copied; wide.rcss keeps
its own.

A second block does the same for the phone's page components (contact rows and card, settings cards and rows: the
rules under `.shell-layer-compact` whose first class is in PAGE_KEEP), so the Contacts and Settings pages of the wide
layout look like the phone's. Page layout, the bars and the visibility classes (`settings-phone-only`) are not copied.

  python3 -I scripts/ui/gen_wide_phone_rules.py            rewrite the generated blocks
  python3 -I scripts/ui/gen_wide_phone_rules.py --check    exit 1 if they are out of date

Generated blocks sit between the BEGIN / END lines at the end of wide.rcss and of colors.rcss.tmpl (the template one is
inside the @media block). After a change run gen_theme_colors.py too. Never edit inside the blocks by hand.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
THEMES = ROOT / "assets" / "themes"
COMPONENTS = THEMES / "components.rcss"
TEMPLATE = THEMES / "colors.rcss.tmpl"
WIDE = THEMES / "wide.rcss"

PHONE = ".shell-chat-overlay"
WIDE_ROOT = ".shell-body--wide"
BEGIN = "/* BEGIN phone message rules (generated by scripts/ui/gen_wide_phone_rules.py, do not edit) */"
END = "/* END phone message rules */"

PAGE_PHONE = ".shell-layer-compact"
PAGE_BEGIN = "/* BEGIN phone page rules (generated by scripts/ui/gen_wide_phone_rules.py, do not edit) */"
PAGE_END = "/* END phone page rules */"
# The first class of a phone selector that is a page component worth copying.
PAGE_KEEP = re.compile(
    r"^\.(contacts-(row|section-header|trust-badge|unread|empty|detail|actions|index|list)|contact-detail-|cd-|"
    r"group-|me-card|me-home|me-invite-qr|me-profile-avatar|settings-(section|mock|q-btn|choice|pill|copied|dev|device|"
    r"step|label|note-row|text-btn|transfer|improve)|ai-look-picker|storage-section|home-composer-mount)")
# ...except these (the visibility classes, and the page's own scroll and padding which wide.rcss lays out itself).
# The Contacts row itself (its box, its separators, its pressed and selected fills) is wide.rcss's: a rounded row like the
# Chats list, not the phone's flat row with a hairline.
PAGE_DROP = re.compile(
    r"settings-(phone|desktop)-only|settings-(banner|warn-row)|contacts-list(-view)?\b|contacts-panel|contacts-header\b|"
    r"contacts-row(\.contacts-row--active|:active|:nth-last-of-type\(2\) \.contacts-row-body)?$|contacts-row-body$")

KEEP = re.compile(
    r"\.(bubble|chat-quote|chat-attachment|chat-audio|chat-file|chat-voice|chat-system-line|chat-date|chat-group-name|"
    r"chat-group-invite|chat-reaction|chat-foot|chat-call-row|chat-row-avatar|chat-row-body|sender-label)")
DROP = re.compile(r"prompt-|header|composer|chat-messages-wrap|chat-panel|shell-|\.messages|\.message-row(-[a-z-]+)?\s*(,|$)")
ONLY_RE = re.compile(r"^\s*/\*\s*@only\s+(light|dark)\s*\*/\s*$")
END_RE = re.compile(r"^\s*/\*\s*@end\s*\*/\s*$")


def top_level_rules(text):
    """[(selector_text, full_text, section)] for the rules at depth 0 of `text`; section is the @only theme or None."""
    rules, depth, i, n = [], 0, 0, len(text)
    sel_start, section = 0, None
    line_start = 0
    while i < n:
        c = text[i]
        if text.startswith("/*", i):
            j = text.index("*/", i) + 2
            i = j
            continue
        if c == "\n" and depth == 0:
            line = text[line_start:i]
            m = ONLY_RE.match(line)
            if m:
                section, sel_start = m.group(1), i + 1
            elif END_RE.match(line):
                section, sel_start = None, i + 1
            line_start = i + 1
        if c == "{":
            if depth == 0:
                sel_text = text[sel_start:i]
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                body = text[sel_start:i + 1]
                clean = re.sub(r"/\*.*?\*/", "", sel_text, flags=re.S).strip()
                rules.append((clean, body.strip("\n"), section))
                sel_start = i + 1
        i += 1
    return rules


def phone_selectors(selector_text):
    out = []
    for part in selector_text.split(","):
        part = part.strip()
        if not part.startswith(PHONE + " "):
            continue
        rest = part[len(PHONE):].strip()
        if KEEP.search(rest) and not DROP.search(rest):
            out.append(WIDE_ROOT + " " + rest)
    return out


def page_selectors(selector_text):
    out = []
    for part in selector_text.split(","):
        part = part.strip()
        if not part.startswith(PAGE_PHONE + " "):
            continue
        rest = part[len(PAGE_PHONE):].strip()
        if PAGE_KEEP.search(rest) and not PAGE_DROP.search(rest):
            out.append(WIDE_ROOT + " " + rest)
    return out


def render(text, template, selectors=phone_selectors):
    chunks = []
    for selector_text, full, section in top_level_rules(text):
        sels = selectors(selector_text)
        if not sels:
            continue
        body = full[full.index("{"):]
        rule = ",\n".join(sels) + " " + body
        if section:
            rule = f"/* @only {section} */\n{rule}\n/* @end */"
        chunks.append(rule)
    return "\n\n".join(chunks) + "\n"


def splice(path, generated, inside_media_block, begin=BEGIN, end=END, text=None):
    text = path.read_text(encoding="utf-8") if text is None else text
    block = f"{begin}\n{generated}{end}\n"
    if begin in text:
        a = text.index(begin)
        b = text.index(end) + len(end) + 1
        return text[:a] + block + text[b:]
    if inside_media_block:
        k = text.rstrip().rfind("}")
        return text[:k] + "\n" + block + "}\n"
    return text.rstrip("\n") + "\n\n" + block


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    comp = COMPONENTS.read_text(encoding="utf-8")
    tmpl = TEMPLATE.read_text(encoding="utf-8")
    # The template's rules live inside the one @media block: scan its body.
    tmpl_body = tmpl[tmpl.index("{", tmpl.index("@media")) + 1:]
    targets = [
        (WIDE, render(comp, False), False, BEGIN, END),
        (TEMPLATE, render(tmpl_body, True), True, BEGIN, END),
        (WIDE, render(comp, False, page_selectors), False, PAGE_BEGIN, PAGE_END),
        (TEMPLATE, render(tmpl_body, True, page_selectors), True, PAGE_BEGIN, PAGE_END),
    ]
    stale = False
    pending = {}
    for path, generated, in_media, begin, end in targets:
        current = pending.get(path, path.read_text(encoding="utf-8"))
        pending[path] = splice(path, generated, in_media, begin, end, current)
    for path, new in pending.items():
        if new != path.read_text(encoding="utf-8"):
            stale = True
            if not args.check:
                path.write_text(new, encoding="utf-8")
                print("wrote", path)
    if args.check and stale:
        print("phone message rules in the wide layout are out of date: run scripts/ui/gen_wide_phone_rules.py")
        sys.exit(1)
    print("ok" if not stale or args.check else "done")


if __name__ == "__main__":
    main()
