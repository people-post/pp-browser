// Generates src/lib/ui/PinyinInitials.inc: the pinyin initial (A-Z) of every CJK Unified Ideograph U+4E00-U+9FFF,
// one character per code point, '#' where the system transliteration gives no Latin letter. The phone Contacts
// list sorts and sections Chinese names by it (NameIndex.h); the table is checked in so every platform has it.
//
// Run on a Mac (it uses the system's ICU Han-Latin transform, which picks each character's most common reading):
//   swift scripts/ui/gen_pinyin_initials.swift src/lib/ui/PinyinInitials.inc
import Foundation

let first: UInt32 = 0x4E00
let last: UInt32 = 0x9FFF
let perLine = 96

guard CommandLine.arguments.count == 2 else {
  FileHandle.standardError.write("usage: swift gen_pinyin_initials.swift <output .inc>\n".data(using: .utf8)!)
  exit(2)
}

var letters = [Character]()
letters.reserveCapacity(Int(last - first + 1))
for code in first...last {
  var initial: Character = "#"
  if let scalar = Unicode.Scalar(code),
     let latin = String(Character(scalar)).applyingTransform(.toLatin, reverse: false)?
       .applyingTransform(.stripDiacritics, reverse: false)?.uppercased(),
     let head = latin.unicodeScalars.first, head.value >= 65, head.value <= 90 {
    initial = Character(head)
  }
  letters.append(initial)
}

var out = "// Generated by scripts/ui/gen_pinyin_initials.swift; do not edit.\n"
out += "// Pinyin initial of U+\(String(first, radix: 16, uppercase: true))..U+\(String(last, radix: 16, uppercase: true)), one per code point ('#' = none).\n"
var index = 0
while index < letters.count {
  let end = min(index + perLine, letters.count)
  out += "\"" + String(letters[index..<end]) + "\"\n"
  index = end
}
try! out.write(toFile: CommandLine.arguments[1], atomically: true, encoding: .utf8)
