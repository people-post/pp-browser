#!/usr/bin/env python3
"""Generate assets/themes/colors-light.rcss and colors-dark.rcss.

Workflow
  1. Edit assets/themes/theme_tokens.tsv (token, light, dark, note) for values, or
     assets/themes/colors.rcss.tmpl for rule structure (selectors, properties).
  2. Run:   python3 -I scripts/ui/gen_theme_colors.py
     (never edit colors-light.rcss / colors-dark.rcss by hand)
  3. Run:   python3 -I scripts/check/check_theme_colors.py
     (fails on any hard-coded colour outside the generated files and the TSV)
  CI/local gate: python3 -I scripts/ui/gen_theme_colors.py --check

Template conventions
  * A placeholder written with double braces around a token name is replaced by that
    token's value for the theme being generated; the placeholder {{theme}} becomes
    "light" or "dark".
  * The comment block at the very top of the template (before the first non-comment
    line) is documentation for the template and is not copied to the output.
  * Theme-only lines: a line holding only  /* @only light */  (or dark) starts a section
    kept for that theme alone; a line holding only  /* @end */  closes it. Sections do not
    nest; they may wrap whole rules or single property lines inside a shared rule.
  * Tokens: one per distinct (light, dark) pair. '-' means "not used in that theme"; a
    token with '-' in a theme may only appear in a section for the other theme.

Options: --check (exit 1 if files on disk differ), --out DIR (write elsewhere, for
scratch comparisons).
"""
import argparse
import re
import sys
from pathlib import Path

HEADER = ("/* GENERATED by scripts/ui/gen_theme_colors.py from theme_tokens.tsv + "
          "colors.rcss.tmpl — do not edit by hand */\n")
THEMES = ("light", "dark")
ONLY_RE = re.compile(r"^\s*/\*\s*@only\s+(light|dark)\s*\*/\s*$")
END_RE = re.compile(r"^\s*/\*\s*@end\s*\*/\s*$")
PLACEHOLDER_RE = re.compile(r"\{\{(\w+)\}\}")


def load_tokens(path):
    tokens = {}
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if n == 1 or not line.strip():
            continue  # header row
        cols = line.split("\t")
        if len(cols) < 3 or cols[0] in tokens:
            sys.exit(f"{path}:{n}: bad or duplicate token row")
        tokens[cols[0]] = {"light": cols[1], "dark": cols[2]}
    return tokens


def strip_prologue(lines):
    i, in_c = 0, False
    while i < len(lines):
        s = lines[i].strip()
        if in_c or s.startswith("/*") or not s:
            in_c = in_c or ("*/" not in s)
            if in_c and "*/" in s:
                in_c = False
            i += 1
        else:
            break
    return lines[i:]


def render(template, tokens, theme, used):
    out, only = [], None
    for n, line in enumerate(strip_prologue(template.splitlines()), 1):
        m = ONLY_RE.match(line)
        if m:
            if only:
                sys.exit(f"template: nested @only near body line {n}")
            only = m.group(1)
            continue
        if END_RE.match(line):
            if not only:
                sys.exit(f"template: @end without @only near body line {n}")
            only = None
            continue
        if only and only != theme:
            continue

        def sub(mm):
            name = mm.group(1)
            if name == "theme":
                return theme
            if name not in tokens:
                sys.exit(f"template: unknown token {name}")
            used.add(name)
            v = tokens[name][theme]
            if v == "-":
                sys.exit(f"template: token {name} has no {theme} value but is used in {theme}")
            return v

        out.append(PLACEHOLDER_RE.sub(sub, line))
    if only:
        sys.exit("template: unterminated @only section")
    return HEADER + "\n".join(out) + "\n"


def main():
    here = Path(__file__).resolve().parent
    root = here.parent.parent
    ap = argparse.ArgumentParser(description="Generate the theme colour files.")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", type=Path, default=root / "assets" / "themes")
    args = ap.parse_args()

    themes_dir = root / "assets" / "themes"
    tokens = load_tokens(themes_dir / "theme_tokens.tsv")
    template = (themes_dir / "colors.rcss.tmpl").read_text(encoding="utf-8")
    used, bad = set(), []
    for theme in THEMES:
        text = render(template, tokens, theme, used)
        target = args.out / f"colors-{theme}.rcss"
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != text:
                bad.append(target)
        else:
            args.out.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
            print(f"wrote {target}")
    unused = sorted(set(tokens) - used)
    if unused:
        print("error: unused tokens in theme_tokens.tsv: " + ", ".join(unused), file=sys.stderr)
        return 1
    if bad:
        for b in bad:
            print(f"out of date: {b} (run scripts/ui/gen_theme_colors.py)", file=sys.stderr)
        return 1
    if args.check:
        print("theme colour files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
